// sweep finds and deletes node_modules and framework build/cache folders
// (.svelte-kit, .turbo, .next, ...) under a directory.
package main

import (
	"bufio"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"runtime"
	"runtime/debug"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/devloop01/sweep/internal/sweep"
)

var version = "dev" // set with -ldflags "-X main.version=..."

const usage = `sweep — find and delete node_modules and framework build/cache folders
(.svelte-kit, .turbo, .next, ...) under a directory.

Usage:
  sweep [flags] [DIR]    DIR defaults to the current directory

Flags:
  -n, --dry-run   only list what would be deleted
  -y, --yes       delete without asking
  -b, --build     also include dist/ build/ out/
  -d, --deploy    also include .vercel .netlify .wrangler — not pure cache:
                  .vercel/.netlify hold the project link (re-run ` + "`vercel link`" + `),
                  .wrangler holds local D1/KV/R2 dev data, which is lost
  -h, --help      show this help
      --version   print the version

Everything in the default list is regenerated by pnpm/npm install or the
next dev/build run. That includes .vercel/output; the rest of .vercel is kept.
`

// env is everything run needs from the outside world, so tests can fake it.
type env struct {
	home           string   // resolved home folder
	system         []string // refused system roots
	stdin          io.Reader
	isTTY          bool // stdin is a terminal
	stdout, stderr io.Writer
	workers        int
}

func main() {
	home, err := os.UserHomeDir()
	if err == nil {
		home, err = filepath.EvalSymlinks(home)
	}
	if err != nil {
		home = "" // CheckRoot refuses to run without a home folder
	}
	fi, err := os.Stdin.Stat()
	isTTY := err == nil && fi.Mode()&os.ModeCharDevice != 0
	if bi, ok := debug.ReadBuildInfo(); ok && version == "dev" && bi.Main.Version != "" && bi.Main.Version != "(devel)" {
		version = bi.Main.Version // go install ...@v1.2.3
	}
	os.Exit(run(os.Args[1:], env{
		home: home, system: sweep.SystemRoots,
		stdin: os.Stdin, isTTY: isTTY, stdout: os.Stdout, stderr: os.Stderr,
		workers: runtime.NumCPU(),
	}))
}

func run(args []string, e env) int {
	fs := flag.NewFlagSet("sweep", flag.ContinueOnError)
	fs.SetOutput(e.stderr)
	fs.Usage = func() {}
	var dryRun, yes, build, deploy, showVersion bool
	for _, f := range []struct {
		p           *bool
		short, long string
	}{{&dryRun, "n", "dry-run"}, {&yes, "y", "yes"}, {&build, "b", "build"}, {&deploy, "d", "deploy"}} {
		fs.BoolVar(f.p, f.short, false, "")
		fs.BoolVar(f.p, f.long, false, "")
	}
	fs.BoolVar(&showVersion, "version", false, "")

	// flag stops at the first positional, so take it and keep parsing to
	// allow flags after DIR. Everything after "--" is positional.
	var dirs []string
	for {
		if err := fs.Parse(args); err != nil {
			if errors.Is(err, flag.ErrHelp) {
				fmt.Fprint(e.stdout, usage)
				return 0
			}
			fmt.Fprint(e.stderr, usage)
			return 2
		}
		rest := fs.Args()
		if len(rest) == 0 {
			break
		}
		if n := len(args) - len(rest); n > 0 && args[n-1] == "--" {
			dirs = append(dirs, rest...)
			break
		}
		dirs, args = append(dirs, rest[0]), rest[1:]
	}
	if showVersion {
		fmt.Fprintln(e.stdout, version)
		return 0
	}
	if len(dirs) > 1 {
		fmt.Fprintf(e.stderr, "sweep: expected at most one DIR, got %d\n%s", len(dirs), usage)
		return 2
	}
	dir := "."
	if len(dirs) == 1 {
		dir = dirs[0]
	}

	root, err := sweep.Resolve(dir)
	if err == nil {
		err = sweep.CheckRoot(root, e.home, e.system)
	}
	if err != nil {
		fmt.Fprintln(e.stderr, "sweep:", printable(err.Error()))
		return 1
	}

	targets := sweep.NewTargets(build, deploy)
	fmt.Fprintf(e.stdout, "Scanning %s ...\n", printable(root))
	cands := sweep.Scan(root, targets, e.workers)
	if len(cands) == 0 {
		fmt.Fprintln(e.stdout, "Nothing to clean.")
		return 0
	}
	var total int64
	for _, c := range cands {
		rel, _ := filepath.Rel(root, c.Path)
		fmt.Fprintf(e.stdout, "%10s  %s\n", human(c.Size), printable(rel))
		total += c.Size
	}
	fmt.Fprintf(e.stdout, "----\n%d folders, %s\n", len(cands), human(total))

	if dryRun {
		fmt.Fprintln(e.stdout, "Dry run: nothing deleted.")
		return 0
	}
	if !yes && !confirm(e) {
		fmt.Fprintln(e.stdout, "Cancelled.")
		return 0
	}

	deleted, errs := sweep.Remove(root, targets, cands, e.workers)
	var freed int64
	for _, c := range deleted {
		freed += c.Size
	}
	for _, err := range errs {
		fmt.Fprintln(e.stderr, "sweep:", printable(err.Error()))
	}
	if len(errs) > 0 {
		fmt.Fprintf(e.stdout, "Deleted %d of %d folders, freed about %s.\n", len(deleted), len(cands), human(freed))
		return 1
	}
	fmt.Fprintf(e.stdout, "Deleted %d folders, freed about %s.\n", len(deleted), human(freed))
	return 0
}

// confirm asks once. Only y/yes proceeds; EOF or a non-terminal stdin cancels.
func confirm(e env) bool {
	fmt.Fprint(e.stdout, "Delete all of these? [y/N] ")
	if !e.isTTY {
		fmt.Fprintln(e.stdout)
		fmt.Fprintln(e.stderr, "sweep: stdin is not a terminal; use --yes to delete without asking.")
		return false
	}
	line, err := bufio.NewReader(e.stdin).ReadString('\n')
	if err != nil {
		fmt.Fprintln(e.stdout)
		return false
	}
	answer := strings.ToLower(strings.TrimSpace(line))
	return answer == "y" || answer == "yes"
}

// human formats bytes with base 1024 and one decimal.
func human(b int64) string {
	const k = 1024.0
	switch f := float64(b); {
	case f >= k*k*k:
		return fmt.Sprintf("%.1f GB", f/(k*k*k))
	case f >= k*k:
		return fmt.Sprintf("%.1f MB", f/(k*k))
	default:
		return fmt.Sprintf("%.1f KB", f/k)
	}
}

// printable replaces control and format characters (newlines, bidi
// overrides, zero-width) and invalid UTF-8 with '?', so a folder name can't
// spoof the list.
func printable(s string) string {
	return strings.Map(func(r rune) rune {
		if r == utf8.RuneError || unicode.In(r, unicode.Cc, unicode.Cf) {
			return '?'
		}
		return r
	}, s)
}
